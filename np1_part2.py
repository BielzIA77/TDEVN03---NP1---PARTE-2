class Aluno:
    def __init__(self, nome: str, nota1: float, nota2: float):
        self.nome = nome
        self.nota1 = nota1
        self.nota2 = nota2

    def calcular_media(self) -> float:
        return (self.nota1 + self.nota2) / 2

    def verificar_situacao(self) -> str:
        media = self.calcular_media()
        if media >= 7.0:
            return "Aprovado"
        else:
            return "Reprovado"

# Solicitar dados do usuário
nome_input = input("Digite o nome do aluno: ")
nota1_input = float(input("Digite a primeira nota: "))
nota2_input = float(input("Digite a segunda nota: "))

# Criar objeto da classe Aluno
aluno = Aluno(nome_input, nota1_input, nota2_input)

# Exibir resultados
media_final = aluno.calcular_media()
situacao_final = aluno.verificar_situacao()

print("\n--- Resultado Final ---")
print(f"Aluno: {aluno.nome}")
print(f"Nota 1: {aluno.nota1:.1f}")
print(f"Nota 2: {aluno.nota2:.1f}")
print(f"Média: {media_final:.1f}")
print(f"Situação: {situacao_final}")